"""aicv CLI — `check`, `report`, `ci` commands."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from . import __version__
from .engine import (apply_baseline, build_verdict, changed_files, exit_code,
                     load_baseline, load_config, render_sarif, run_checks,
                     save_baseline, save_report, severity_counts)


def _cmd_check(args, root: Path) -> int:
    files = changed_files(root, staged=args.staged)
    if not files:
        target = "staged" if args.staged else "diff HEAD"
        print(f"aicv: no changed .py/.js/.ts files for target '{target}' — nothing to verify.")
        return 0
    return _scan(args, root, files, "staged" if args.staged else "diff HEAD")


def _cmd_ci(args, root: Path) -> int:
    import os
    base = os.environ.get("GITHUB_BASE_REF")
    if not base:
        print("aicv ci: GITHUB_BASE_REF is not set; falling back to 'origin/main'.",
              file=sys.stderr)
        base = "origin/main"
    files = changed_files(root, base_ref=base)
    if not files:
        print(f"aicv ci: no changed files vs {base} — nothing to verify.")
        return 0
    return _scan(args, root, files, f"ci vs {base}")


def _scan(args, root: Path, files, target: str) -> int:
    enabled = load_config(root)
    findings = run_checks(root, files, enabled, use_ruff=not args.no_ruff)
    baseline_note = None
    if getattr(args, "baseline", False):
        keys = load_baseline(root)
        if keys is None:
            print("aicv: --baseline set but .aicv/baseline.json not found — "
                  "run `aicv baseline` first.", file=sys.stderr)
            return 2
        total = len(findings)
        findings = apply_baseline(findings, keys)
        baseline_note = (f"baseline: {total - len(findings)} known finding(s) "
                         f"suppressed, {len(findings)} new")
    md = save_report(root, target, files, findings)
    counts = {"error": 0, "warning": 0}
    for f in findings:
        counts[f["severity"]] += 1
    human = [
        f"aicv: checked {len(files)} file(s) [{target}] — "
        f"{counts['error']} error(s), {counts['warning']} warning(s)",
        *[f"  [{f['severity'].upper()}] {f['file']}:{f['line']} ({f['rule']}) {f['message']}"
          for f in sorted(findings, key=lambda x: (x["severity"], x["file"], x["line"]))],
        f"report: {md}",
    ]
    if baseline_note:
        human.insert(1, baseline_note)
    rc = exit_code(findings)
    if getattr(args, "sarif", False):
        import json as _j
        sarif_path = root / ".aicv" / "latest.sarif"
        sarif_path.write_text(
            _j.dumps(render_sarif(findings), indent=2, ensure_ascii=False),
            encoding="utf-8")
        human.append(f"sarif: {sarif_path}")
    if getattr(args, "json", False):
        # machine-readable verdict for agent-loop integration: stdout carries
        # only the JSON; human-readable output goes to stderr.
        import json as _j
        verdict = build_verdict(files, findings)
        print(_j.dumps(verdict, ensure_ascii=False))
        for line in human:
            print(line, file=sys.stderr)
    else:
        for line in human:
            print(line)
    return rc


def _cmd_baseline(args, root: Path) -> int:
    """Record the current findings as accepted legacy debt (.aicv/baseline.json)."""
    files = changed_files(root, staged=args.staged)
    if not files:
        target = "staged" if args.staged else "diff HEAD"
        print(f"aicv baseline: no changed .py/.js/.ts files for target '{target}' "
              f"— nothing to record.")
        return 0
    enabled = load_config(root)
    findings = run_checks(root, files, enabled, use_ruff=not args.no_ruff)
    p = save_baseline(root, findings)
    counts = severity_counts(findings)
    print(f"aicv baseline: recorded {len(findings)} finding(s) "
          f"({counts.get('error', 0)} error(s), {counts.get('warning', 0)} warning(s)) "
          f"-> {p}")
    print("aicv baseline: `aicv check --baseline` will now fail only on NEW findings.")
    return 0


def _cmd_init(args, root: Path) -> int:
    target = root / ".aicv.toml"
    if target.is_file() and not args.force:
        print("aicv init: .aicv.toml already exists — use --force to overwrite.")
        return 2
    from .checks import RULES
    lines = [
        "# aicv configuration — generated by `aicv init`.",
        "# Toggle individual rules; missing keys fall back to defaults.",
        "",
        "[rules]",
    ]
    for rid, spec in sorted(RULES.items()):
        lines.append(f"{rid} = {str(spec['default']).lower()}  # {spec['name']}")
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"aicv init: wrote {target}")
    return 0


def _cmd_report(args, root: Path) -> int:
    d = root / ".aicv"
    if args.json:
        p = d / "latest.json"
    elif getattr(args, "sarif", False):
        p = d / "latest.sarif"
    else:
        p = d / "latest.md"
    if not p.is_file():
        print(f"aicv report: no report found at {p} — run `aicv check` first.")
        return 2
    print(p.read_text(encoding="utf-8"))
    return 0


def _cmd_verdict(args, root: Path) -> int:
    """Agent-loop marker: runs the scan and prints a parseable verdict block
    on stdout. Does not write .aicv/ report artifacts."""
    files = changed_files(root, staged=args.staged)
    target = "staged" if args.staged else "diff HEAD"
    if not files:
        print(f"=== AICV VERDICT: PASS | target={target} | files=0 errors=0 warnings=0 ===")
        return 0
    enabled = load_config(root)
    findings = run_checks(root, files, enabled, use_ruff=not args.no_ruff)
    counts = severity_counts(findings)
    verdict = "FAIL" if exit_code(findings) else "PASS"
    marker = (f"=== AICV VERDICT: {verdict} | target={target} "
              f"| files={len(files)} errors={counts.get('error', 0)} "
              f"warnings={counts.get('warning', 0)} ===")
    if args.summary:
        print(marker)
    else:
        print(marker)
        for f in sorted(findings, key=lambda x: (x["severity"], x["file"], x["line"])):
            print(f"[{f['severity'].upper()}] {f['file']}:{f['line']} "
                  f"({f['rule']}) {f['message']}")
        print("=== AICV VERDICT END ===")
    return exit_code(findings)


def build_parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(prog="aicv",
                                 description="Verification gate for AI-generated code")
    ap.add_argument("--version", action="version", version=f"aicv {__version__}")
    sub = ap.add_subparsers(dest="command", required=True)

    p_check = sub.add_parser("check", help="verify changed files (git diff HEAD or --staged)")
    p_check.add_argument("--staged", action="store_true", help="only staged changes")
    p_check.add_argument("--no-ruff", action="store_true", help="skip ruff even if installed")
    p_check.add_argument("--json", action="store_true",
                         help="print a machine-readable verdict JSON to stdout "
                              "(agent-loop integration)")
    p_check.add_argument("--sarif", action="store_true",
                         help="also write a SARIF 2.1.0 report (.aicv/latest.sarif) "
                              "for GitHub code scanning")
    p_check.add_argument("--baseline", action="store_true",
                         help="fail only on NEW findings not recorded in "
                              ".aicv/baseline.json (see `aicv baseline`)")
    p_check.set_defaults(func=_cmd_check)

    p_rep = sub.add_parser("report", help="print the latest verification report")
    p_rep.add_argument("--json", action="store_true", help="print JSON instead of markdown")
    p_rep.add_argument("--sarif", action="store_true", help="print the SARIF report")
    p_rep.set_defaults(func=_cmd_report)

    p_init = sub.add_parser("init", help="generate a starter .aicv.toml in this repo")
    p_init.add_argument("--force", action="store_true",
                        help="overwrite an existing .aicv.toml")
    p_init.set_defaults(func=_cmd_init)

    p_ci = sub.add_parser("ci", help="CI mode: diff vs GITHUB_BASE_REF")
    p_ci.add_argument("--no-ruff", action="store_true")
    p_ci.add_argument("--json", action="store_true")
    p_ci.add_argument("--sarif", action="store_true")
    p_ci.set_defaults(func=_cmd_ci)

    p_baseline = sub.add_parser(
        "baseline", help="record current findings as accepted legacy debt "
                         "(.aicv/baseline.json)")
    p_baseline.add_argument("--staged", action="store_true", help="only staged changes")
    p_baseline.add_argument("--no-ruff", action="store_true")
    p_baseline.set_defaults(func=_cmd_baseline)

    p_verdict = sub.add_parser(
        "verdict", help="agent-loop marker verdict (no report files written)")
    p_verdict.add_argument("--staged", action="store_true")
    p_verdict.add_argument("--no-ruff", action="store_true")
    p_verdict.add_argument("--summary", action="store_true",
                           help="single marker line only")
    p_verdict.set_defaults(func=_cmd_verdict)
    return ap


def main(argv=None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    root = Path.cwd()
    return args.func(args, root)


if __name__ == "__main__":
    sys.exit(main())
